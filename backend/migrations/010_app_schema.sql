BEGIN;

CREATE TABLE app.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.sessions (
    id uuid PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES app.users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX sessions_user_id_idx ON app.sessions (user_id);

CREATE TABLE app.model_settings (
    id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    settings jsonb NOT NULL DEFAULT '{}'::jsonb,
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.customer_scores (
    customer_id bigint PRIMARY KEY REFERENCES public.accounts(id) ON DELETE CASCADE,
    score double precision,
    level text NOT NULL,
    loyalty double precision,
    expected_loss_cents bigint NOT NULL DEFAULT 0 CHECK (expected_loss_cents >= 0),
    reasons jsonb NOT NULL DEFAULT '[]'::jsonb,
    data_warnings jsonb NOT NULL DEFAULT '[]'::jsonb,
    model_version integer NOT NULL DEFAULT 1,
    calculated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE app.service_scores (
    service_id bigint PRIMARY KEY REFERENCES public.services(id) ON DELETE CASCADE,
    customer_id bigint NOT NULL REFERENCES public.accounts(id) ON DELETE CASCADE,
    score double precision,
    feature_contributions jsonb NOT NULL DEFAULT '[]'::jsonb,
    value_cents bigint NOT NULL DEFAULT 0 CHECK (value_cents >= 0),
    expected_loss_cents bigint NOT NULL DEFAULT 0 CHECK (expected_loss_cents >= 0),
    model_version integer NOT NULL DEFAULT 1,
    calculated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX service_scores_customer_id_idx ON app.service_scores (customer_id);

CREATE TABLE app.service_status_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id bigint NOT NULL,
    old_status text,
    new_status text NOT NULL,
    changed_at timestamptz NOT NULL
);

CREATE INDEX service_status_events_changed_at_idx
    ON app.service_status_events (changed_at);

CREATE TABLE app.source_meta (
    id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    captured_at timestamptz,
    loaded_at timestamptz NOT NULL DEFAULT now(),
    account_count integer NOT NULL DEFAULT 0,
    service_count integer NOT NULL DEFAULT 0,
    transaction_count integer NOT NULL DEFAULT 0
);

COMMIT;